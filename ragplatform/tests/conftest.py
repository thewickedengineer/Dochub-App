class FakeDochub:
    """Records the callbacks the worker makes — a stand-in for the .NET API's endpoints."""

    def __init__(self) -> None:
        self.calls: list[tuple[str, dict]] = []
        self.fail_paths: set[str] = set()

    def handler(self, request: httpx.Request) -> httpx.Response:
        assert request.headers["X-Dochub-Service-Key"] == "t" * 40
        body = json.loads(request.content or b"{}")
        self.calls.append((request.url.path, body))
        if any(request.url.path.endswith(p) for p in self.fail_paths):
            return httpx.Response(503, text="down")
        if "/api/ingestion/artifacts/" in request.url.path:
            return httpx.Response(200, json={"artifactStatus": "Processed", "sourceStatus": "Processed"})
        return httpx.Response(200, json={"status": "ok"})

    def paths(self, suffix: str) -> list[str]:
        return [p for p, _ in self.calls if p.endswith(suffix)]


