async def upload_fixtures(settings: Settings, names: list[str], container: str) -> list[dict]:
    """Puts fixture files in Azurite the way Dochub's extractor would."""
    service = BlobServiceClient.from_connection_string(settings.blob_connection_string.get_secret_value())
    try:
        try:
            await service.create_container(container)
        except Exception:  # noqa: BLE001 — already exists
            pass
        documents = []
        for name in names:
            data = (FIXTURES / name).read_bytes()
            path = f"teams/claims/groups/claims-it/artifacts/core/20261001T000000000Z/{name}"
            await service.get_blob_client(container, path).upload_blob(data, overwrite=True)
            documents.append({
                "documentId": str(uuid.uuid5(uuid.NAMESPACE_URL, name)),
                "name": name, "relativePath": name, "blobPath": path,
                "blobUrl": f"http://127.0.0.1:10000/devstoreaccount1/{container}/{path}",
                "sizeBytes": len(data), "contentType": None,
                "checksumSha256": hashlib.sha256(data).hexdigest(), "revision": 1,
                "contentMd5": base64.b64encode(hashlib.md5(data).digest()).decode(),
                "documentVersionId": str(uuid.uuid4()), "sourceType": "Local", "externalId": None,
            })
        return documents
    finally:
        await service.close()


