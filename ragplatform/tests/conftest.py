async def enqueue(settings: Settings, body: dict, message_id: str | None = None) -> None:
    async with await psycopg.AsyncConnection.connect(settings.dochub_queue_dsn) as conn:
        await conn.execute(
            "INSERT INTO dochub.queue_messages (queue, message_id, subject, payload, status, "
            "delivery_count, created_at) VALUES (%s, %s, %s, %s, 0, 0, now())",
            (settings.process_queue, message_id or f"process-{uuid.uuid4().hex}",
             "dochub.documents.process.requested", json.dumps(body)),
        )
        await conn.commit()


async def queue_row(settings: Settings) -> dict:
    async with await psycopg.AsyncConnection.connect(settings.dochub_queue_dsn) as conn:
        row = await (await conn.execute(
            "SELECT status, delivery_count, error, locked_until FROM dochub.queue_messages ORDER BY id DESC LIMIT 1"
        )).fetchone()
    return {"status": row[0], "delivery_count": row[1], "error": row[2], "locked_until": row[3]}
